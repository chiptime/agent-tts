"""Crew TLS material from the Python stdlib alone.

``cryptography`` is deliberately not a dependency: everything the crew
link needs is either ``ssl`` (contexts) or the local ``openssl``
binary (certificate generation). Certificates are self-signed and
long-lived — the PIN is the limit of trust, not the expiry — and they
are generated by openssl, never hand-rolled in Python:

    openssl req -x509 -newkey rsa:2048 -keyout crew.key -out crew.crt \
        -days 3650 -nodes -subj "/CN=<host>"

The client context pins exactly one certificate: it loads that
certificate as its ONLY trust anchor and requires a certificate
(``CERT_REQUIRED``), so the handshake itself fails for any server
identity other than the pinned one. Hostnames are not checked — the
pin is the identity, and tailnet names change more often than
operators re-issue certificates.
"""

from __future__ import annotations

import base64
import binascii
import re
import shutil
import ssl
import subprocess
from pathlib import Path
from typing import Optional

CERT_SUBJECT_DAYS = 3650  # ~10 years: the pin is the trust, not the expiry


class CrewTlsError(Exception):
    """TLS material problems the operator must fix (missing openssl, a
    bad PEM). Never a crash and never ignored."""


def pem_to_der(pem: str) -> bytes:
    """The DER bytes of the FIRST certificate in a PEM string.

    This is PEM plumbing (base64 between the markers), not X.509
    parsing: the crew never interprets certificate contents, it only
    hashes them.
    """
    if not isinstance(pem, str):
        raise CrewTlsError("certificate PEM must be a string")
    match = re.search(
        r"-----BEGIN CERTIFICATE-----(.*?)-----END CERTIFICATE-----",
        pem,
        re.DOTALL,
    )
    if match is None:
        raise CrewTlsError("no CERTIFICATE block found in PEM")
    b64 = re.sub(r"\s+", "", match.group(1))
    try:
        return base64.b64decode(b64, validate=True)
    except (binascii.Error, ValueError) as exc:
        raise CrewTlsError(f"certificate PEM body is not valid base64: {exc}") from exc


def pin_of_der(der: bytes) -> str:
    """The SHA-256 pin of certificate DER bytes (hex)."""
    import hashlib

    return hashlib.sha256(der).hexdigest()


def pin_of_pem(pem: str) -> str:
    """The SHA-256 pin of a PEM certificate — the value the roster
    stores under ``cert_sha256_pin``."""
    return pin_of_der(pem_to_der(pem))


def pinned_client_context(cert_pem: str) -> ssl.SSLContext:
    """A client SSLContext that trusts EXACTLY one certificate.

    The pinned certificate is loaded as the only trust anchor and
    ``CERT_REQUIRED`` is kept, so the handshake verifies the server
    against the pin itself — no CA store, no default paths, no
    hostname matching. A different server certificate fails the
    handshake; a pin check in the application layer is never reached
    because the TLS layer already refused.
    """
    pem_to_der(cert_pem)  # fail early on a bad PEM, before any context
    context = ssl.SSLContext(ssl.PROTOCOL_TLS_CLIENT)
    # NOTE: set_default_verify_paths() is intentionally never called —
    # the system CA store must not be able to vouch for a crew member.
    context.check_hostname = False  # the pin is the identity, not the name
    context.verify_mode = ssl.CERT_REQUIRED
    context.load_verify_locations(cadata=cert_pem)
    return context


def server_ssl_context(
    cert_file, key_file, ca_file, *, require_client: bool = True
) -> ssl.SSLContext:
    """The crew listener's server context: this host's certificate,
    plus client-certificate verification against a bundle of the
    ENROLLED members' certificates.

    ``require_client=False`` (CERT_OPTIONAL) is the enrolment-window
    stance: a candidate peer presents a certificate the roster does
    not know yet, so the handshake cannot require it — the enrolment
    route authenticates by join token instead, and every other crew
    route still fails closed in the application-layer two-factor
    check (``auth.check_crew_auth`` needs the DER, so a client without
    a certificate authenticates as nobody).
    """
    context = ssl.SSLContext(ssl.PROTOCOL_TLS_SERVER)
    context.load_cert_chain(str(cert_file), keyfile=str(key_file))
    context.load_verify_locations(cafile=str(ca_file))
    context.verify_mode = ssl.CERT_REQUIRED if require_client else ssl.CERT_OPTIONAL
    return context


def openssl_self_signed_command(
    host: str, cert_path: str, key_path: str, days: int = CERT_SUBJECT_DAYS
) -> str:
    """The exact openssl invocation that mints this host's crew
    certificate — printed by the CLI when the binary is missing so the
    operator can run it by hand. One line, no prompts (``-nodes``,
    ``-subj``), validity bounded only by the pin discipline."""
    return (
        f"openssl req -x509 -newkey rsa:2048"
        f" -keyout {key_path} -out {cert_path}"
        f" -days {days} -nodes -subj /CN={host}"
    )


def ensure_host_certificate(
    directory, host: str, *, days: int = CERT_SUBJECT_DAYS
) -> tuple[Path, Path, str]:
    """This host's crew certificate, generated on first use.

    Returns ``(cert_path, key_path, pin)``. Existing material is
    reused as-is: a regenerated certificate is a new identity, and
    identity changes must be explicit (re-enrolment), never a startup
    side effect. Generation shells out to the local ``openssl`` — the
    one X.509 writer this project trusts; when the binary is missing
    the error carries the exact command to run by hand.
    """
    directory = Path(directory)
    directory.mkdir(parents=True, exist_ok=True, mode=0o700)
    cert_path = directory / "crew.crt"
    key_path = directory / "crew.key"
    if cert_path.exists() and key_path.exists():
        try:
            pin = pin_of_pem(cert_path.read_text(encoding="utf-8"))
            return cert_path, key_path, pin
        except CrewTlsError:
            # unreadable material is regenerated below, not trusted
            pass

    if shutil.which("openssl") is None:
        raise CrewTlsError(
            "openssl binary not found; generate the crew certificate by hand:\n"
            + openssl_self_signed_command(host, str(cert_path), str(key_path), days)
        )
    result = subprocess.run(
        [
            "openssl", "req", "-x509", "-newkey", "rsa:2048",
            "-keyout", str(key_path), "-out", str(cert_path),
            "-days", str(days), "-nodes", "-subj", f"/CN={host}",
        ],
        capture_output=True,
        text=True,
    )
    if result.returncode != 0 or not cert_path.exists():
        raise CrewTlsError(
            "openssl failed to generate the crew certificate:\n"
            + (result.stderr or result.stdout or "").strip()
        )
    import os

    try:
        os.chmod(key_path, 0o600)
        os.chmod(cert_path, 0o600)
    except OSError:
        pass
    return cert_path, key_path, pin_of_pem(cert_path.read_text(encoding="utf-8"))
